def _rust_test_fn(op: str) -> str:
    fn_name = f"contract_{pascal_to_snake(op)}"
    call = render_rust_call(op)
    is_unit = _is_rust_unit(op)
    is_raw = _is_rust_raw(op)

    # Stubs always return 200 with a schema-shaped body, so any Err is a
    # contract failure (transport error, 4xx/5xx surfaced as Err, or
    # deserialization failure).  We unwrap unconditionally and let the
    # panic-style failure surface in the test report.
    if is_unit:
        body = textwrap.dedent(f"""\
            let config = make_config();
            {call}.await.expect("contract violation: stub returned non-2xx or transport error");""")
    elif is_raw:
        body = textwrap.dedent(f"""\
            let config = make_config();
            let resp = {call}
                .await
                .expect("contract violation: stub returned non-2xx or transport error");
            assert!(
                resp.status().is_success(),
                "contract violation: status = {{}}",
                resp.status()
            );""")
    else:
        body = textwrap.dedent(f"""\
            let config = make_config();
            {call}
                .await
                .expect("contract violation: stub returned non-2xx or transport error");""")

    return (
        f"#[tokio::test]\n"
        f"async fn {fn_name}() {{\n" + textwrap.indent(body, "    ") + "\n}"
    )


# ---------------------------------------------------------------------------
# Rust generator — Mustache template driven.
# ---------------------------------------------------------------------------
#
# This path mirrors the openapi-generator template-driven approach: build a
# bundle (``Map<String, Object>`` in JMustache, plain ``dict`` here), hand
# it to the renderer, let ``ci/cts/templates/rust_wiremock.mustache`` produce
# the file body.  The bundle is intentionally minimal — two pre-rendered
# string slots (``uses`` and ``tests``) — so the static harness lives
# entirely inside the template (and its ``partial_rust_harness`` partial)
# rather than in a Python ``textwrap.dedent`` literal.
# ---------------------------------------------------------------------------


def generate_rust_mustache(ops: list[str], renderer: TemplateRenderer) -> str:
    used_modules = sorted({RUST_API_MODULE[op] for op in ops})
    uses_lines = [
        "use lance_namespace_reqwest_client::apis::configuration::Configuration;",
        "use lance_namespace_reqwest_client::apis::{" + ", ".join(used_modules) + "};",
        "use lance_namespace_reqwest_client::models;",
    ]
    bundle = {
        "uses": "\n".join(uses_lines),
        "tests": "\n\n".join(_rust_test_fn(op) for op in ops),
    }
    return renderer.render("rust_wiremock", bundle)


# ---------------------------------------------------------------------------
# Mustache-based Python generator (engine="mustache").
# ---------------------------------------------------------------------------
#
# Mirrors the Rust path: build a tiny bundle with the already-rendered
# ``tests`` block and let ``python_wiremock.mustache`` stitch it together
# with the static harness partial.  Imports inside individual test bodies
# are still emitted by ``_python_test_fn`` because they vary per op (each
# test imports just the api class + models it uses).
# ---------------------------------------------------------------------------


def generate_python_mustache(ops: list[str], renderer: TemplateRenderer) -> str:
    bundle = {
        "tests": "\n\n".join(_python_test_fn(op) for op in ops),
    }
    return renderer.render("python_wiremock", bundle)


# ---------------------------------------------------------------------------
# Mustache-based Java Apache generator (engine="mustache").
# ---------------------------------------------------------------------------
#
# The full test class is split into:
#   * static partial-style frame in ``java_apache_wiremock.mustache``
#   * ``imports_block`` — pre-rendered ``import org.lance.namespace.…;`` lines
#   * ``methods`` — all ``@Test`` methods joined into a single string
#
# Triple-stash (``{{{ }}}``) is used for both string slots since the raw
# Java is already valid and must not be HTML-escaped.
# ---------------------------------------------------------------------------


def generate_java_apache_mustache(
    ops: list[str], renderer: TemplateRenderer
) -> str:
    pkgs = _JAVA_CLIENT_PACKAGES["apache"]
    imports = _collect_java_api_imports(
        ops, pkgs["client"]
    ) + _collect_java_model_imports(pkgs["model"])
    bundle = {
        "imports_block": "\n".join(f"import {i};" for i in imports),
        "methods": "\n\n".join(_java_apache_test_method(op) for op in ops),
    }
    return renderer.render("java_apache_wiremock", bundle)


