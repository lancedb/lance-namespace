# Tokens matching a PascalCase identifier in a PYTHON_CALL expression.
_PY_PASCAL_TOKEN_RE = re.compile(r"\b([A-Z][A-Za-z0-9]*)\b")


def _python_model_imports_for(call: str) -> list[str]:
    """Return the sorted list of model class names referenced by `call`.

    Filters PascalCase tokens through ``PYTHON_MODEL_CLASSES`` so only valid
    generated model classes are kept (excludes call-site names like ``True``,
    ``None``, helper class names, etc.).
    """
    seen: list[str] = []
    for m in _PY_PASCAL_TOKEN_RE.finditer(call):
        token = m.group(1)
        if token in PYTHON_MODEL_CLASSES and token not in seen:
            seen.append(token)
    return sorted(seen)


def _python_test_fn(op: str) -> str:
    fn_name = f"test_{pascal_to_snake(op)}"
    api_mod = PYTHON_API_MODULE[op]
    call = render_python_call(op)
    is_none = _is_python_none(op)

    # API class name (one per generated *_api.py module).  Convention:
    # ``foo_bar_api`` -> ``FooBarApi``; derived from the module stem so we
    # don't need a hand-maintained snake→Pascal map.
    api_cls = "".join(part.capitalize() for part in api_mod.split("_"))

    # imports inside test function body — all indented with 4 spaces
    model_imports = _python_model_imports_for(call)

    import_lines = [
        f"    from lance_namespace_urllib3_client.api.{api_mod} import {api_cls}"
    ]

    for model in model_imports:
        snake_model = PYTHON_MODEL_CLASSES[model]
        import_lines.append(
            f"    from lance_namespace_urllib3_client.models.{snake_model} import {model}"
        )

    imports_block = ("\n".join(import_lines) + "\n") if import_lines else ""

    # Stubs always return 200 with a schema-shaped body, so any raised
    # exception (transport error, deserialization failure, 4xx/5xx) is a
    # contract violation.  We let it propagate so pytest reports a real
    # failure with the original traceback.
    if is_none:
        body = (
            f"def {fn_name}(api_client: ApiClient) -> None:\n"
            f'    """{op} completes without error against the WireMock stub."""\n'
            + imports_block
            + f"    api = {api_cls}(api_client)\n"
            f"    {call}\n"
        )
    else:
        body = (
            f"def {fn_name}(api_client: ApiClient) -> None:\n"
            f'    """{op} returns a deserializable response against the WireMock stub."""\n'
            + imports_block
            + f"    api = {api_cls}(api_client)\n"
            f"    result = {call}\n"
            # Some ops legitimately return ``None`` (typeless Object schema /
            # empty body), so we only assert that the call did not raise.
            f"    del result\n"
        )
    return body


