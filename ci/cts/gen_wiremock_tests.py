# Files inside the api dirs that are not API classes themselves.
_SKIP_RUST_FILES = {"configuration.rs", "mod.rs"}
_SKIP_PYTHON_FILES = {"__init__.py"}


def _scan_rust_apis(apis_dir: Path) -> dict[str, str]:
    """Return {OperationPascalName: module_stem} by scanning Rust apis dir.

    e.g. `list_namespaces` defined in `namespace_api.rs` →
         {"ListNamespaces": "namespace_api"}.
    """
    fn_re = re.compile(r"^pub\s+async\s+fn\s+([a-z_][a-z0-9_]*)\s*\(", re.MULTILINE)
    result: dict[str, str] = {}
    for rs_file in sorted(apis_dir.glob("*.rs")):
        if rs_file.name in _SKIP_RUST_FILES:
            continue
        module_stem = rs_file.stem  # e.g. "namespace_api"
        text = rs_file.read_text(encoding="utf-8")
        for m in fn_re.finditer(text):
            op = _snake_to_pascal(m.group(1))
            result.setdefault(op, module_stem)
    return result


def _scan_python_apis(
    apis_dir: Path,
) -> tuple[dict[str, list[str]], dict[str, str]]:
    """Return ``(modules_map, return_types)`` from scanning Python api dir.

    * ``modules_map``: ``{OperationPascalName: [module_stem, ...]}`` (multi-tag).
    * ``return_types``: ``{OperationPascalName: python_return_annotation}``,
      e.g. ``"None"``, ``"CreateTableResponse"``, ``"int"``.

    Python is multi-tag: the same operation lives in multiple ``*_api.py``
    files with identical signatures.  Return types come from the public
    method's ``-> X:`` annotation, which the generator emits at the bottom of
    the parameter list.  Helper variants (``*_with_http_info``,
    ``*_without_preload_content``) are ignored.
    """
    # Top-level public method = exactly 4-space indented, no leading underscore,
    # and we filter out the helper suffixes generated by openapi-generator.
    method_re = re.compile(r"^    def ([a-z][a-z0-9_]*)\(", re.MULTILINE)
    # Matches the closing-paren + return annotation that follows every method.
    return_re = re.compile(r"^    \)\s*->\s*([^:]+):\s*$", re.MULTILINE)
    helper_suffixes = ("_with_http_info", "_without_preload_content")
    modules_map: dict[str, list[str]] = {}
    return_types: dict[str, str] = {}
    for py_file in sorted(apis_dir.glob("*.py")):
        if py_file.name in _SKIP_PYTHON_FILES:
            continue
        module_stem = py_file.stem  # e.g. "namespace_api"
        text = py_file.read_text(encoding="utf-8")
        # Pair each `def name(` with the next `) -> Ret:` to recover the
        # return type without parsing the whole signature.
        defs = list(method_re.finditer(text))
        rets = list(return_re.finditer(text))
        # Two-pointer walk: for each def, find the first ret-line after it.
        ret_iter = iter(rets)
        next_ret = next(ret_iter, None)
        for d in defs:
            # Advance ret_iter until we find a ret-line after this def.
            while next_ret is not None and next_ret.start() < d.end():
                next_ret = next(ret_iter, None)
            method = d.group(1)
            if method.startswith("_") or method == "__init__":
                continue
            if any(method.endswith(suf) for suf in helper_suffixes):
                continue
            op = _snake_to_pascal(method)
            modules_map.setdefault(op, []).append(module_stem)
            if next_ret is not None:
                return_types.setdefault(op, next_ret.group(1).strip())
    return modules_map, return_types


def _scan_java_apis(
    apis_dirs: tuple[Path, ...],
) -> tuple[dict[str, list[str]], dict[str, str]]:
    """Return ``(groups_map, return_types)`` from scanning Java api dirs.

    * ``groups_map``: ``{OperationPascalName: [group, ...]}`` (multi-tag).
    * ``return_types``: ``{OperationPascalName: java_return_type}`` (e.g.
      ``"void"``, ``"byte[]"``, ``"CreateTableResponse"``, ``"Map<String, String>"``).
      Captured exactly once per op — overloads carry the same return type, so
      first occurrence wins.

    e.g. ``alterTableAddColumns`` lives in ``DataApi.java`` and ``TableApi.java`` →
    ``{"AlterTableAddColumns": ["data", "table"]}``.  The group is the
    lower-cased class-name prefix before "Api".
    """
    # Match the public op methods (skip internal `*WithHttpInfo` helpers
    # which are caught via the dedup `seen_in_file` below).  Captures the
    # return type so callers can derive ``void`` / ``byte[]`` classification
    # without a parallel hand-written table.
    method_re = re.compile(
        r"^  public\s+(?P<ret>[\w<>,\s\[\]\.]+?)\s+(?P<name>[a-z][A-Za-z0-9_]*)\s*\(",
        re.MULTILINE,
    )
    # Boilerplate generated by openapi-generator on every Api class.
    ignore_methods = {
        "setApiClient",
        "getApiClient",
        "invokeAPI",
        "getHostIndex",
        "setHostIndex",
        "getCustomBaseUrl",
        "setCustomBaseUrl",
    }
    groups_map: dict[str, list[str]] = {}
    return_types: dict[str, str] = {}
    for apis_dir in apis_dirs:
        if not apis_dir.is_dir():
            continue
        for java_file in sorted(apis_dir.glob("*Api.java")):
            cls = java_file.stem  # e.g. "NamespaceApi"
            if not cls.endswith("Api"):
                continue
            group = cls[: -len("Api")].lower()  # "Namespace" → "namespace"
            text = java_file.read_text(encoding="utf-8")
            seen_in_file: set[str] = set()
            for m in method_re.finditer(text):
                method = m.group("name")
                if method in ignore_methods:
                    continue
                if method in seen_in_file:
                    continue  # collapse overloads — same op
                seen_in_file.add(method)
                op = _camel_to_pascal(method)
                # ``ret`` may carry the ``CompletableFuture<...>`` wrapper for
                # the async client; unwrap once so callers see the inner type.
                ret = m.group("ret").strip()
                inner = re.match(r"^CompletableFuture<\s*(.+)\s*>$", ret)
                if inner:
                    ret = inner.group(1).strip()
                # Map ``Void`` (boxed) → ``void`` so the rest of the generator
                # only has to handle one form for "no body".
                if ret == "Void":
                    ret = "void"
                groups = groups_map.setdefault(op, [])
                if group not in groups:
                    groups.append(group)
                return_types.setdefault(op, ret)
    return groups_map, return_types


def _scan_cross_cutting_tags(spec_path: Path) -> set[str]:
    """Identify cross-cutting OpenAPI tags from ``docs/src/spec.yaml``.

    Domain tags in this spec all use the form ``Operations that are related
    to <X>``; cross-cutting tags (``Metadata``, ``Data``) instead describe
    *how* operations behave (e.g. "computationally lightweight / intensive").
    We use the presence of ``computationally`` in the description as the
    signal — it cleanly separates "by-object" tags from "by-cost" tags
    without a hand-maintained list.

    Returns a set containing both the bare tag stem and its Python module
    form, e.g. ``{"metadata", "metadata_api", "data", "data_api"}``.  This
    lets the same set drive both the Java picker (which sees groups like
    ``"metadata"``) and the Python picker (which sees modules like
    ``"metadata_api"``).  Falls back to an empty set if the spec is
    unreadable so the generator stays robust against transient layout
    changes.
    """
    if not spec_path.is_file():
        return set()
    text = spec_path.read_text(encoding="utf-8")
    # Locate the top-level ``tags:`` block.  We deliberately do not pull in
    # PyYAML — the layout is stable enough for a tiny line scanner.
    out: set[str] = set()
    in_tags = False
    current_name: str | None = None
    current_desc: list[str] = []

    def _flush() -> None:
        if current_name and any("computationally" in line for line in current_desc):
            stem = current_name.lower()
            # Both forms so the same set works for Java groups ("metadata")
            # and Python modules ("metadata_api").
            out.add(stem)
            out.add(f"{stem}_api")

    for raw_line in text.splitlines():
        if not in_tags:
            if raw_line.rstrip() == "tags:":
                in_tags = True
            continue
        # Leaving the tags block: a new top-level YAML key (no leading space).
        if raw_line and not raw_line.startswith((" ", "\t", "#")):
            _flush()
            break
        stripped = raw_line.strip()
        if stripped.startswith("- name:"):
            _flush()
            current_name = stripped[len("- name:") :].strip()
            current_desc = []
        elif (
            stripped
            and current_name is not None
            and not stripped.startswith("description:")
        ):
            current_desc.append(stripped)
    else:
        _flush()
    return out


def _pick_narrowest_tag(
    tags: list[str],
    tag_op_count: dict[str, int],
    cross_cutting: set[str],
) -> str:
    """Pick the most specific tag for an operation hosted by multiple tags.

    Generic over both Python module names (``namespace_api``) and Java
    group stems (``namespace``) — caller decides which keyspace
    ``tag_op_count`` and ``cross_cutting`` use.

    Two-stage selection:
      1. Prefer a non-cross-cutting candidate (cross-cutting tags are
         ``Metadata``/``Data``-style horizontal classifiers, identified
         dynamically from the spec — see ``_scan_cross_cutting_tags``).
      2. Among the remaining candidates, pick the tag that hosts the
         fewest operations overall (= "narrowest" tag).  Ties break
         alphabetically for deterministic output.
    """
    domain = [t for t in tags if t not in cross_cutting] or tags
    return min(domain, key=lambda t: (tag_op_count.get(t, 0), t))


# Matches the generated `from lance_namespace_urllib3_client.models.<snake>
# import <Pascal>` lines inside models/__init__.py.
_PY_MODEL_IMPORT_RE = re.compile(
    r"^from\s+lance_namespace_urllib3_client\.models\.([a-z][a-z0-9_]*)"
    r"\s+import\s+([A-Z][A-Za-z0-9_]*)\s*$",
    re.MULTILINE,
)


def _scan_python_models(models_dir: Path) -> dict[str, str]:
    """Return {PascalCaseModelClass: snake_case_module_stem} from models/__init__.py.

    The generated `models/__init__.py` re-exports every model with a stable
    `from lance_namespace_urllib3_client.models.<snake> import <Pascal>`
    pattern.  We parse it instead of round-tripping snake↔Pascal heuristics so
    edge cases (e.g. `JSONArrowDataType` ↔ `json_arrow_data_type.py`) stay
    accurate.
    """
    init_file = models_dir / "__init__.py"
    if not init_file.is_file():
        return {}
    result: dict[str, str] = {}
    for m in _PY_MODEL_IMPORT_RE.finditer(init_file.read_text(encoding="utf-8")):
        snake, pascal = m.group(1), m.group(2)
        result[pascal] = snake
    return result


def discover_api_classification(repo_root: Path) -> None:
    """Populate the three module-level classification dicts from generated code.

    Must be called before any generator that consumes JAVA_API_CLASS /
    RUST_API_MODULE / PYTHON_API_MODULE.
    """
    rust_dir = repo_root / _DEFAULT_RUST_APIS_DIR
    rust_models_dir = repo_root / _DEFAULT_RUST_MODELS_DIR
    python_dir = repo_root / _DEFAULT_PYTHON_APIS_DIR
    python_models_dir = repo_root / _DEFAULT_PYTHON_MODELS_DIR
    java_dirs = tuple(repo_root / p for p in _DEFAULT_JAVA_APIS_DIRS)
    spec_path = repo_root / "docs" / "src" / "spec.yaml"

    missing = [
        p
        for p in (rust_dir, rust_models_dir, python_dir, python_models_dir)
        if not p.is_dir()
    ]
    # For Java, at least one of the client dirs must exist.
    if not any(p.is_dir() for p in java_dirs):
        missing.extend(java_dirs)
    if missing:
        raise SystemExit(
            "ERROR: cannot discover API classification — generated client(s) "
            "missing:\n  "
            + "\n  ".join(str(p) for p in missing)
            + "\nRun `make gen` (or the per-language gen target) first."
        )

    RUST_API_MODULE.clear()
    RUST_API_MODULE.update(_scan_rust_apis(rust_dir))

    # Cross-cutting tags (Metadata/Data-style) identified from the spec so
    # the picker prefers a domain tag whenever one is available.  Used by
    # both the Java and Python pickers below.
    cross_cutting = _scan_cross_cutting_tags(spec_path)

    java_multi, java_returns = _scan_java_apis(java_dirs)
    # How many operations each Java group hosts overall — drives the
    # "narrowest tag wins" heuristic in _pick_narrowest_tag.
    java_group_op_count: dict[str, int] = {}
    for groups in java_multi.values():
        for g in groups:
            java_group_op_count[g] = java_group_op_count.get(g, 0) + 1
    JAVA_API_CLASS.clear()
    for op, groups in java_multi.items():
        JAVA_API_CLASS[op] = _pick_narrowest_tag(
            groups, java_group_op_count, cross_cutting
        )
    JAVA_RETURN_TYPE.clear()
    JAVA_RETURN_TYPE.update(java_returns)

    python_multi, python_returns = _scan_python_apis(python_dir)
    # How many operations each *_api.py module hosts in total — drives the
    # "narrowest tag wins" heuristic in _pick_narrowest_tag.
    module_op_count: dict[str, int] = {}
    for modules in python_multi.values():
        for m in modules:
            module_op_count[m] = module_op_count.get(m, 0) + 1
    PYTHON_API_MODULE.clear()
    for op, modules in python_multi.items():
        PYTHON_API_MODULE[op] = _pick_narrowest_tag(
            modules, module_op_count, cross_cutting
        )
    PYTHON_RETURN_TYPE.clear()
    PYTHON_RETURN_TYPE.update(python_returns)

    PYTHON_MODEL_CLASSES.clear()
    PYTHON_MODEL_CLASSES.update(_scan_python_models(python_models_dir))

    # Drives FIXTURES → call-expression synthesis for all three languages.
    OPERATIONS.clear()
    OPERATIONS.update(_scan_rust_signatures(rust_dir))

    # Required-field order needed for Rust ``models::Foo::new(...)`` calls.
    _MODEL_REQUIRED.clear()
    _MODEL_REQUIRED.update(_scan_rust_model_required(rust_models_dir))


