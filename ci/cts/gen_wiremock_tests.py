# ---------------------------------------------------------------------------
# Model required-field registry — drives Rust positional ``::new()`` args.
# ---------------------------------------------------------------------------
#
# Parsed lazily from ``rust/.../src/models/*.rs`` by extracting the
# ``pub fn new(<args>) -> Self`` signature of each model.  The parameter list
# of ``new`` is the canonical required-field order used by the Rust client.
# ---------------------------------------------------------------------------

_MODEL_REQUIRED: dict[str, list[str]] = {}
# {ModelClass: {field_name: (rust_type_str, is_option)}} — built from
# ``pub <field>: <type>,`` lines inside ``pub struct Cls { ... }``.  Used by
# the Rust renderer to pick the right numeric suffix (i32 vs i64 vs f32) and
# to decide whether non-required kwargs need a ``Some(...)`` wrapper.
_MODEL_FIELDS: dict[str, dict[str, tuple[str, bool]]] = {}

# Match `pub fn new(<args>) -> Cls` inside an `impl Cls { ... }` block.
_RUST_MODEL_IMPL_RE = re.compile(
    r"^impl\s+(?P<cls>[A-Z][A-Za-z0-9]*)\s*\{",
    re.MULTILINE,
)
_RUST_MODEL_NEW_RE = re.compile(
    r"pub\s+fn\s+new\s*\(\s*(?P<args>[^)]*)\)\s*->\s*[A-Z][A-Za-z0-9]*\s*\{",
    re.DOTALL,
)


def _parse_rust_struct_fields(body: str) -> dict[str, tuple[str, bool]]:
    """Parse ``pub <name>: <type>,`` declarations from a struct body.

    Tracks angle-bracket depth so that types containing ``,`` (such as
    ``Option<HashMap<String, String>>``) are read as a single token.
    Returns ``{field_name: (inner_type, is_option)}`` where ``inner_type``
    has the outer ``Option<>`` stripped iff ``is_option`` is True.
    """
    fields: dict[str, tuple[str, bool]] = {}
    i = 0
    n = len(body)
    while i < n:
        # Locate the next "pub <name>:" — only outside of nested braces, which
        # struct bodies never contain.
        m = re.compile(r"pub\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*").search(body, i)
        if not m:
            break
        name = m.group(1)
        j = m.end()
        depth = 0
        type_start = j
        while j < n:
            ch = body[j]
            if ch == "<":
                depth += 1
            elif ch == ">":
                depth -= 1
            elif ch == "," and depth == 0:
                break
            elif ch == "\n" and depth == 0:
                # Field terminated by newline without comma (rare); stop here.
                break
            j += 1
        ftype = body[type_start:j].strip().rstrip(",").strip()
        is_opt = ftype.startswith("Option<") and ftype.endswith(">")
        inner = ftype[len("Option<") : -1].strip() if is_opt else ftype
        fields[name] = (inner, is_opt)
        i = j + 1
    return fields


def _scan_rust_model_required(models_dir: Path) -> dict[str, list[str]]:
    """Return {ModelClass: [required_field_name, ...]} from models/*.rs.

    The order of arguments to ``pub fn new(...)`` matches the canonical
    required-field order needed when invoking ``models::Foo::new(...)``.

    Side effect: also populates the module-level ``_MODEL_FIELDS`` map with
    ``{ModelClass: {field_name: is_option}}`` parsed from the ``pub struct``
    declaration.
    """
    result: dict[str, list[str]] = {}
    _MODEL_FIELDS.clear()
    for rs_file in sorted(models_dir.glob("*.rs")):
        if rs_file.name == "mod.rs":
            continue
        text = rs_file.read_text(encoding="utf-8")
        # Collect struct field optionality first.  Use a depth-aware parser
        # because field types like ``Option<HashMap<String, String>>`` contain
        # commas inside angle brackets.
        for sm in re.finditer(
            r"pub\s+struct\s+(?P<cls>[A-Z][A-Za-z0-9]*)\s*\{",
            text,
        ):
            cls = sm.group("cls")
            # Walk forward from the opening ``{`` until matching ``}``.
            depth = 1
            k = sm.end()
            while k < len(text) and depth > 0:
                if text[k] == "{":
                    depth += 1
                elif text[k] == "}":
                    depth -= 1
                k += 1
            body = text[sm.end() : k - 1]
            _MODEL_FIELDS[cls] = _parse_rust_struct_fields(body)
        # An impl block may contain ``pub fn new``; capture the class then
        # search forward for the first matching ``new`` signature.
        for impl_m in _RUST_MODEL_IMPL_RE.finditer(text):
            cls = impl_m.group("cls")
            tail = text[impl_m.end() :]
            new_m = _RUST_MODEL_NEW_RE.search(tail)
            if not new_m:
                continue
            args = new_m.group("args").strip()
            if not args:
                result[cls] = []
                continue
            new_fields: list[str] = []
            for raw in _split_params(args):
                if ":" not in raw:
                    continue
                name, _ = raw.split(":", 1)
                new_fields.append(name.strip())
            result[cls] = new_fields
    return result


def _model_required_fields(cls: str) -> list[str]:
    """Return the ordered required-field list for ``cls``.

    Surfaces a clear error if the model is unknown — typically a sign the
    fixture references a model that the Rust client did not generate.
    """
    if cls not in _MODEL_REQUIRED:
        raise SystemExit(
            f"ERROR: model class '{cls}' not found in generated Rust client. "
            "Either the Rust client is stale (run `make gen-rust`) or the "
            "fixture references a model that does not exist."
        )
    return _MODEL_REQUIRED[cls]


