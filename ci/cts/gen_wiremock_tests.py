def _rust_numeric_suffix(rust_type: str | None) -> str:
    """Return the literal suffix matching a Rust scalar type hint."""
    if rust_type is None:
        return ""
    t = rust_type.strip()
    if t in ("i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "f32", "f64"):
        return t
    return ""


def _rust_element_type(rust_type: str | None) -> str | None:
    """For ``Vec<T>`` return ``T``; else None."""
    if rust_type is None:
        return None
    t = rust_type.strip()
    if t.startswith("Vec<") and t.endswith(">"):
        return t[4:-1].strip()
    return None


def _rust_literal(value: object, type_hint: str | None = None) -> str:
    """Render an AbstractValue as a Rust expression.

    ``type_hint`` is the expected Rust type for ``value`` (e.g. ``"i32"``,
    ``"f32"``, ``"Vec<f32>"``).  Used to pick the right numeric literal
    suffix when emitting integers / floats.
    """
    if isinstance(value, ModelValue):
        cls = value.class_name
        # Two construction strategies, picked based on whether the fixture
        # supplies any *optional* fields (kwargs that are not in the model's
        # ``new()`` required arg list):
        #
        # 1. Only required fields supplied → ``models::Cls::new(<positional>)``
        #    (matches the model's canonical constructor).
        # 2. Extra (optional) fields supplied → struct literal
        #    ``models::Cls { field: value, ..Default::default() }``
        #    (every generated model derives ``Default``, so this is safe).
        required = _model_required_fields(cls)
        model_fields = _MODEL_FIELDS.get(cls, {})
        positional_args: list[str] = []
        missing_required: list[str] = []
        used: set[str] = set()
        for fname in required:
            if fname not in value.kwargs:
                missing_required.append(fname)
                continue
            ft = model_fields.get(fname, ("", False))[0] or None
            positional_args.append(_rust_literal(value.kwargs[fname], ft))
            used.add(fname)
        if missing_required:
            raise SystemExit(
                f"ERROR: model {cls} requires fields {missing_required} but "
                f"fixture provided only {list(value.kwargs)}."
            )
        extra = [k for k in value.kwargs if k not in used]
        if not extra:
            return f"models::{cls}::new({', '.join(positional_args)})"

        # Struct-literal path: every supplied kwarg is rendered as a field
        # initializer.  Required-field types are non-Option in Rust, so they
        # need no wrapping; optional fields are ``Option<T>`` and need
        # ``Some(...)``.
        parts: list[str] = []
        for fname, fval in value.kwargs.items():
            field_type, is_opt = model_fields.get(fname, ("", False))
            rendered = _rust_literal(fval, field_type or None)
            if is_opt:
                rendered = f"Some({rendered})"
            parts.append(f"{fname}: {rendered}")
        # Any field neither required-supplied nor optional-supplied falls back
        # to ``Default::default()``.
        return f"models::{cls} {{ " + ", ".join(parts) + ", ..Default::default() }"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        # Use the type-hint suffix when known (e.g. i32 for ``k: i32``), else
        # default to i64 — callers/fields wanting i32 will supply the hint.
        suffix = _rust_numeric_suffix(type_hint) or "i64"
        return f"{value}{suffix}"
    if isinstance(value, float):
        suffix = _rust_numeric_suffix(type_hint) or "f32"
        return f"{value}{suffix}"
    if isinstance(value, str):
        # Choose `"…"` for &str fixture slots vs `"…".to_string()` for String
        # ones — but at render time we don't know which slot we are filling.
        # Heuristic: callers handle &str path-parameters by going through
        # ``_rust_arg`` (which strips the ``.to_string()`` for &str).  Default
        # output here is an owned String literal, because every model field
        # using a string is ``String`` in Rust.
        return f"{json.dumps(value)}.to_string()"
    if isinstance(value, bytes):
        return "vec![]" if not value else f"vec![{', '.join(str(b) for b in value)}]"
    if isinstance(value, list):
        if not value:
            return "vec![]"
        elem_hint = _rust_element_type(type_hint)
        return "vec![" + ", ".join(_rust_literal(v, elem_hint) for v in value) + "]"
    if isinstance(value, dict):
        if not value:
            return "std::collections::HashMap::new()"
        raise SystemExit(
            "ERROR: non-empty dict fixtures not supported in Rust renderer."
        )
    raise SystemExit(f"ERROR: unsupported fixture value {value!r} in Rust renderer.")


def _rust_arg(op: str, param: Param) -> str:
    """Render one positional argument for a Rust call."""
    value = _fixture_for(op, param)

    if value is None:
        if param.optional:
            return "None"
        raise _missing_fixture(op, param)

    # Optional, fixture provided → wrap in Some(...) using the right inner form.
    inner = _render_rust_inner(param.type, value)
    return f"Some({inner})" if param.optional else inner


def _render_rust_inner(abs_t: AbstractType, value: object) -> str:
    """Render `value` for an unwrapped (non-Option) parameter slot."""
    if abs_t.kind == AbstractType.STRING:
        # Path / query string params take &str — no .to_string().
        if isinstance(value, str):
            return json.dumps(value)
    if abs_t.kind == AbstractType.BYTES:
        return _rust_literal(value)
    if abs_t.kind == AbstractType.STR_MAP:
        return _rust_literal(value)
    if abs_t.kind == AbstractType.I32 and isinstance(value, int):
        return f"{value}i32"
    if abs_t.kind == AbstractType.I64 and isinstance(value, int):
        return f"{value}i64"
    if abs_t.kind == AbstractType.F32 and isinstance(value, (int, float)):
        return f"{float(value)}f32"
    if abs_t.kind == AbstractType.BOOL and isinstance(value, bool):
        return "true" if value else "false"
    if abs_t.kind == AbstractType.MODEL and isinstance(value, ModelValue):
        return _rust_literal(value)
    raise SystemExit(
        f"ERROR: cannot render value {value!r} into Rust slot of type {abs_t}."
    )


def render_rust_call(op: str) -> str:
    """Synthesize the full Rust call expression for ``op``."""
    params, _ = OPERATIONS[op]
    module = RUST_API_MODULE[op]
    fn = pascal_to_snake(op)
    args = ["&config"] + [_rust_arg(op, p) for p in params]
    return f"{module}::{fn}({', '.join(args)})"


# ----- Java ------------------------------------------------------------------


def _rust_type_to_java_suffix(rust_type: str | None) -> str:
    """Pick the Java numeric literal suffix from a Rust scalar type hint.

    Java auto-widens ``int → long`` only at compile-time, but builder setters
    declared as ``Long``/``Float`` reject unboxed ``int``/``double`` literals.
    Mapping:
      * Rust i64       → Java ``L`` suffix
      * Rust f32 / f64 → Java ``f`` suffix (we always emit float, the model
        setters use ``Float`` for f32 fields)
    """
    if rust_type is None:
        return ""
    t = rust_type.strip()
    if t == "i64":
        return "L"
    if t in ("f32", "f64"):
        return "f"
    return ""


def _java_literal(value: object, type_hint: str | None = None) -> str:
    """Render an AbstractValue as a Java expression (builder-style for models).

    ``type_hint`` is the *Rust* type name for ``value`` when known — Rust
    serves as our authoritative type oracle since the Java client mirrors
    the same OpenAPI schema.  We use it to attach ``L``/``f`` suffixes for
    boxed-numeric setters.
    """
    if isinstance(value, ModelValue):
        # Java builders: `new Cls().field1(v1).field2(v2)…`
        cls = value.class_name
        rust_fields = _MODEL_FIELDS.get(cls, {})
        chain = [f"new {cls}()"]
        for fname, fval in value.kwargs.items():
            ft = rust_fields.get(fname, ("", False))[0] or None
            chain.append(f".{_camelize(fname)}({_java_literal(fval, ft)})")
        return "".join(chain)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return f"{value}{_rust_type_to_java_suffix(type_hint)}"
    if isinstance(value, float):
        # All floats default to ``f`` (most Java setters use Float).  If a
        # field really needs ``double`` we can refine later via the hint.
        return f"{value}f"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bytes):
        return (
            "new byte[0]"
            if not value
            else ("new byte[] {" + ", ".join(str(b) for b in value) + "}")
        )
    if isinstance(value, list):
        if not value:
            return "new java.util.ArrayList<>()"
        # Use Arrays.asList(...) for non-empty literal lists.  Element-level
        # hints reuse the Vec<T> element type when available.
        elem_hint = _rust_element_type(type_hint)
        rendered = ", ".join(_java_literal(v, elem_hint) for v in value)
        return f"java.util.Arrays.asList({rendered})"
    if isinstance(value, dict):
        if not value:
            return "new java.util.HashMap<>()"
        raise SystemExit(
            "ERROR: non-empty dict fixtures not supported in Java renderer."
        )
    raise SystemExit(f"ERROR: unsupported fixture value {value!r} in Java renderer.")


def _java_arg(op: str, param: Param) -> str:
    """Render one positional argument for a Java call."""
    value = _fixture_for(op, param)
    if value is None:
        if param.optional:
            return "null"
        raise _missing_fixture(op, param)
    # Java needs `1L` for i64 slots and `1f` for f32 slots — apply suffix here.
    if (
        param.type.kind == AbstractType.I64
        and isinstance(value, int)
        and not isinstance(value, bool)
    ):
        return f"{value}L"
    if (
        param.type.kind == AbstractType.F32
        and isinstance(value, (int, float))
        and not isinstance(value, bool)
    ):
        return f"{float(value)}f"
    return _java_literal(value)


def render_java_call(op: str) -> str:
    """Synthesize the Java apache call expression (`api.method(...)`) for ``op``."""
    params, _ = OPERATIONS[op]
    method = _camelize(pascal_to_snake(op))
    args = [_java_arg(op, p) for p in params]
    return f"api.{method}({', '.join(args)})"


# ----- Python ----------------------------------------------------------------


def _python_literal(value: object) -> str:
    """Render an AbstractValue as a Python expression (kwargs-style for models)."""
    if isinstance(value, ModelValue):
        # Python urllib3 client accepts kwargs constructors.
        kwargs_str = ", ".join(
            f"{k}={_python_literal(v)}" for k, v in value.kwargs.items()
        )
        return f"{value.class_name}({kwargs_str})"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bytes):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_python_literal(v) for v in value) + "]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        # Only str→str maps exist today.
        return (
            "{"
            + ", ".join(
                f"{json.dumps(k)}: {_python_literal(v)}" for k, v in value.items()
            )
            + "}"
        )
    raise SystemExit(f"ERROR: unsupported fixture value {value!r} in Python renderer.")


def render_python_call(op: str) -> str:
    """Synthesize the Python call expression (`api.method(kw=v, ...)`) for ``op``."""
    params, _ = OPERATIONS[op]
    method = pascal_to_snake(op)
    kw: list[str] = []
    for p in params:
        value = _fixture_for(op, p)
        if value is None:
            if p.optional:
                continue
            raise _missing_fixture(op, p)
        kw.append(f"{p.name}={_python_literal(value)}")
    return f"api.{method}({', '.join(kw)})"


