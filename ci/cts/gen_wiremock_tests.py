# Java Apache client — shared helpers used by ``generate_java_apache_mustache``.
# ---------------------------------------------------------------------------
#
# Maps each generated Java client to the package prefix used by both its
# ``api`` subpackage (e.g. ``...client.apache.api.NamespaceApi``) and the
# top-level package shared with ``model`` (e.g. ``org.lance.namespace`` →
# ``org.lance.namespace.model.<Class>``).  Derived from
# ``_DEFAULT_JAVA_APIS_DIRS`` — keep in sync if a new client is added.
_JAVA_CLIENT_PACKAGES: dict[str, dict[str, str]] = {
    "apache": {
        "client": "org.lance.namespace.client.apache",
        "model": "org.lance.namespace.model",
    },
    "async": {
        "client": "org.lance.namespace.client.async",
        "model": "org.lance.namespace.model",
    },
}


def _collect_java_model_imports(model_pkg: str) -> list[str]:
    """Collect every Java model class referenced from a FIXTURES entry.

    Walks the ``FIXTURES`` table (including nested ``ModelValue`` payloads)
    and records the PascalCase class names so we can emit the matching
    ``import <model_pkg>.<Class>;`` lines without a parallel hardcoded
    list.
    """
    seen: set[str] = set()

    def visit(v: object) -> None:
        if isinstance(v, ModelValue):
            seen.add(v.class_name)
            for nested in v.kwargs.values():
                visit(nested)
        elif isinstance(v, list):
            for x in v:
                visit(x)
        elif isinstance(v, dict):
            for x in v.values():
                visit(x)

    for params in FIXTURES.values():
        for value in params.values():
            visit(value)
    return sorted(f"{model_pkg}.{c}" for c in seen)


def _collect_java_api_imports(ops: list[str], client_pkg: str) -> list[str]:
    """Collect ``<client_pkg>.api.<Cls>Api`` imports actually used by ``ops``.

    Drives the ``import ...api.NamespaceApi;`` block from the same
    ``JAVA_API_CLASS`` discovery that drives the ``api_inst`` line, so the
    set of imports is always exactly the set of api classes referenced in
    the body — no manual upkeep.
    """
    classes = {_java_api_class_name(op) for op in ops}
    return sorted(f"{client_pkg}.api.{c}" for c in classes)


def _java_api_class_name(op: str) -> str:
    """Derive the generated ``*Api`` class name (e.g. ``"TableApi"``) for ``op``.

    ``JAVA_API_CLASS`` stores the lowercase group stem captured from the
    Java api-class filenames (``TableApi.java`` → ``"table"``); the class
    itself is the same stem PascalCased with the literal ``Api`` suffix.
    """
    return JAVA_API_CLASS[op].capitalize() + "Api"


def _java_apache_test_method(op: str) -> str:
    """Generate a single @Test method for the Apache client."""
    method_name = pascal_to_camel(op) + "ReturnsValidResponse"
    api_cls = _java_api_class_name(op)
    is_void = _is_java_void(op)
    call = render_java_call(op)

    api_inst = f"{api_cls} api = new {api_cls}(apiClient);"

    # Stubs always return 200 with a schema-shaped body.  Any thrown
    # ApiException — including ``code == 0`` (transport / connection) and
    # 4xx/5xx — therefore indicates a contract violation.  We surface them
    # all by re-throwing.
    if is_void:
        inner = textwrap.dedent(f"""\
            @Test
            void {method_name}() throws ApiException {{
              {api_inst}
              {call};
            }}""")
    elif _is_java_bytes(op):
        inner = textwrap.dedent(f"""\
            @Test
            void {method_name}() throws ApiException {{
              {api_inst}
              {call};
              // Binary response — successful return is the contract assertion.
            }}""")
    else:
        inner = textwrap.dedent(f"""\
            @Test
            void {method_name}() throws ApiException {{
              {api_inst}
              {call};
              // Non-null assertion omitted: some ops legitimately return null
              // when the response schema is typeless Object / empty body.
            }}""")

    return textwrap.indent(inner, "  ")


