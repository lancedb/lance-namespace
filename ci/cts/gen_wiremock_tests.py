# ---------------------------------------------------------------------------
# Dynamic call-expression synthesis
# ---------------------------------------------------------------------------
#
# Instead of maintaining three parallel call tables (RUST_CALL,
# JAVA_APACHE_*_CALLS, PYTHON_CALL), we drive every call expression from a
# single abstract signature parsed from the generated Rust client, plus a
# small central fixture table addressed by ``(operation, parameter_name)``.
#
# Pipeline:
#
#   1. ``_scan_rust_signatures`` parses ``pub async fn <op>(configuration: &..,
#      <params>) -> Result<<return>, _>`` from every ``rust/.../apis/*.rs``,
#      producing for each operation:
#         * a list of ``Param(name, AbstractType, optional)``
#         * an ``AbstractType`` for the success branch of the Result
#   2. ``FIXTURES[op][param_name]`` provides the *value* a contract test should
#      pass for each non-optional parameter.  Optional (``Option<T>``) params
#      default to absent unless an explicit fixture is supplied.
#   3. ``render_call_<lang>(op)`` emits the appropriate call expression by
#      pairing the parsed signature with FIXTURES, using language-specific
#      rules for literals, model constructors and ``None``/``null``/``None``.
#
# When the spec grows a new parameter, only the Rust client has to be
# regenerated; the contract generator inherits the new shape automatically.
# Only the fixture value (if mandatory) needs to be added.
# ---------------------------------------------------------------------------


class AbstractType:
    """Lightweight tagged union describing a parameter / return type.

    The ``kind`` discriminates the variant; ``model``/``element`` carry the
    payload for compound types.  We deliberately keep this small instead of
    pulling in ``dataclasses`` so the generator stays free of optional deps.
    """

    __slots__ = ("kind", "model", "element")

    # Scalars / well-known shapes.
    STRING = "string"
    I32 = "i32"
    I64 = "i64"
    F32 = "f32"
    BOOL = "bool"
    BYTES = "bytes"  # Rust Vec<u8> / Java byte[] / Python bytes
    STR_MAP = "str_map"  # HashMap<String, String>
    UNIT = "unit"  # () return — Result<()>
    RAW_RESPONSE = "raw"  # Rust reqwest::Response return
    MODEL = "model"  # models::Foo  → uses .model
    UNKNOWN = "unknown"

    def __init__(
        self, kind: str, model: str = "", element: "AbstractType | None" = None
    ) -> None:
        self.kind = kind
        self.model = model
        self.element = element

    def __repr__(self) -> str:  # pragma: no cover — debugging aid
        if self.kind == self.MODEL:
            return f"Model({self.model})"
        return self.kind


class Param:
    """A single function parameter as parsed from the Rust signature."""

    __slots__ = ("name", "type", "optional")

    def __init__(self, name: str, type_: AbstractType, optional: bool) -> None:
        self.name = name
        self.type = type_
        self.optional = optional


# Populated by ``_scan_rust_signatures()``: op → (params, return_type).
OPERATIONS: dict[str, tuple[list[Param], AbstractType]] = {}

# Rust scalar / wrapper-type tokens we recognize verbatim.  Anything else falls
# through to ``AbstractType.UNKNOWN`` and surfaces as a generator error.
_RUST_SCALAR_TO_ABSTRACT: dict[str, AbstractType] = {
    "&str": AbstractType(AbstractType.STRING),
    "String": AbstractType(AbstractType.STRING),
    "i32": AbstractType(AbstractType.I32),
    "i64": AbstractType(AbstractType.I64),
    "f32": AbstractType(AbstractType.F32),
    "bool": AbstractType(AbstractType.BOOL),
}

# Matches `pub async fn NAME(configuration: &configuration::Configuration, <rest>) -> Result<<R>, ...> {`
_RUST_FN_SIG_RE = re.compile(
    r"^pub\s+async\s+fn\s+(?P<name>[a-z_][a-z0-9_]*)"
    r"\s*\(\s*configuration:\s*&configuration::Configuration\s*,?\s*"
    r"(?P<rest>[^)]*)\)\s*->\s*Result<\s*(?P<ret>[^,]+?)\s*,",
    re.MULTILINE | re.DOTALL,
)


def _classify_rust_type(rust_type: str) -> tuple[AbstractType, bool]:
    """Return ``(AbstractType, is_optional)`` for a Rust parameter / return type.

    Handles ``Option<T>``, ``Vec<u8>`` (→ Bytes), ``models::Foo`` and the
    scalars listed in ``_RUST_SCALAR_TO_ABSTRACT``.  ``HashMap<String, String>``
    is recognized either qualified (``std::collections::HashMap<...>``) or
    bare.  Returns ``(UNKNOWN, optional)`` if the shape is unfamiliar — the
    caller surfaces this with a clear error.
    """
    rust_type = rust_type.strip()

    optional = False
    m = re.match(r"^Option<\s*(.+)\s*>$", rust_type)
    if m:
        optional = True
        rust_type = m.group(1).strip()

    # Unit return is spelled "()".
    if rust_type == "()":
        return AbstractType(AbstractType.UNIT), optional

    # `reqwest::Response` — raw HTTP response, used only by QueryTable.
    if rust_type == "reqwest::Response":
        return AbstractType(AbstractType.RAW_RESPONSE), optional

    # Bytes body — generated client always uses `Vec<u8>`.
    if rust_type == "Vec<u8>":
        return AbstractType(AbstractType.BYTES), optional

    # Map<String,String> — both fully-qualified and bare forms occur.
    if re.match(
        r"^(std::collections::)?HashMap<\s*String\s*,\s*String\s*>$", rust_type
    ):
        return AbstractType(AbstractType.STR_MAP), optional

    # Model: `models::FooRequest`.
    m = re.match(r"^models::([A-Z][A-Za-z0-9]*)$", rust_type)
    if m:
        return AbstractType(AbstractType.MODEL, model=m.group(1)), optional

    abs_t = _RUST_SCALAR_TO_ABSTRACT.get(rust_type)
    if abs_t is not None:
        return abs_t, optional

    return AbstractType(AbstractType.UNKNOWN), optional


def _split_params(rest: str) -> list[str]:
    """Split a Rust parameter list on top-level commas (ignores generic <,>)."""
    if not rest.strip():
        return []
    parts: list[str] = []
    depth = 0
    buf: list[str] = []
    for ch in rest:
        if ch == "<":
            depth += 1
            buf.append(ch)
        elif ch == ">":
            depth -= 1
            buf.append(ch)
        elif ch == "," and depth == 0:
            parts.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
    if buf:
        parts.append("".join(buf).strip())
    return [p for p in parts if p]


def _scan_rust_signatures(
    apis_dir: Path,
) -> dict[str, tuple[list[Param], AbstractType]]:
    """Parse every ``pub async fn`` in ``apis/*.rs`` into ``OPERATIONS`` entries.

    The Rust client is our single source of truth for the abstract shape of
    each operation: arity, parameter names / types, and the result type.
    """
    result: dict[str, tuple[list[Param], AbstractType]] = {}
    for rs_file in sorted(apis_dir.glob("*.rs")):
        if rs_file.name in _SKIP_RUST_FILES:
            continue
        text = rs_file.read_text(encoding="utf-8")
        for m in _RUST_FN_SIG_RE.finditer(text):
            op = _snake_to_pascal(m.group("name"))
            if op in result:
                # Same operation appears in several tag modules with identical
                # signatures; first occurrence wins, the rest are duplicates.
                continue
            params: list[Param] = []
            for raw in _split_params(m.group("rest")):
                # Each entry is `name: type` (trim trailing comma already gone).
                if ":" not in raw:
                    continue
                name, type_str = raw.split(":", 1)
                abs_t, optional = _classify_rust_type(type_str)
                if abs_t.kind == AbstractType.UNKNOWN:
                    raise SystemExit(
                        f"ERROR: cannot classify Rust parameter '{raw.strip()}' "
                        f"in {rs_file.name}::{m.group('name')} — extend "
                        "_classify_rust_type()."
                    )
                params.append(Param(name.strip(), abs_t, optional))
            ret_t, _ = _classify_rust_type(m.group("ret"))
            # Any leftover scalar non-Bytes / non-Map return type (e.g. `String`,
            # `i64`) is fine; we treat the success branch as opaque.
            result[op] = (params, ret_t)
    return result


# ---------------------------------------------------------------------------
# Central fixture table: (op, param_name) → AbstractValue
# ---------------------------------------------------------------------------
#
# Each entry is the *abstract* value for a parameter — language renderers
# turn it into the appropriate literal/constructor.  Supported shapes:
#
#   * Plain Python scalars: ``str``, ``int``, ``float``, ``bool``, ``bytes``,
#     ``dict`` (only str→str), or ``list`` (empty list literal).
#   * ``ModelValue(class_name, kwargs)`` — instantiates a generated model with
#     a kwargs dict of nested ``AbstractValue`` entries.  Used both for the
#     top-level body parameter and for any nested object fields.
#
# Optional Rust ``Option<T>`` params with no fixture entry default to absent
# (``None``/``null``/Python kwarg omitted).
# ---------------------------------------------------------------------------


class ModelValue:
    """A nested model literal, e.g. ``QueryTableRequest(k=1, vector=...)``."""

    __slots__ = ("class_name", "kwargs")

    def __init__(self, class_name: str, **kwargs: object) -> None:
        self.class_name = class_name
        self.kwargs = kwargs


