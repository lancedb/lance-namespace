def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate WireMock contract test files for all API operations."
    )
    parser.add_argument(
        "--mappings-dir",
        default="build/cts/wiremock/src/main/resources/mappings",
        help="Directory containing WireMock mapping JSON files",
    )
    parser.add_argument(
        "--out-rust",
        default="rust/lance-namespace-reqwest-client/tests/wiremock.rs",
        help="Output path for the Rust contract test file",
    )
    parser.add_argument(
        "--out-python",
        default="python/lance_namespace_urllib3_client/tests/test_wiremock.py",
        help="Output path for the Python contract test file",
    )
    parser.add_argument(
        "--out-java-apache",
        default="java/lance-namespace-apache-client/src/test/java/org/lance/namespace/client/apache/cts/WireMockIT.java",
        help="Output path for the Java Apache client contract test file",
    )
    parser.add_argument(
        "--out-java-async",
        default="java/lance-namespace-async-client/src/test/java/org/lance/namespace/client/async/cts/WireMockIT.java",
        help="Output path for the Java Async client contract test file",
    )
    parser.add_argument(
        "--engine",
        choices=("mustache",),
        default=None,
        help=(
            "Codegen engine. Only ``mustache`` is supported (templates "
            "under ``ci/cts/templates/`` rendered via chevron). The flag "
            "is retained for backward compatibility with CI scripts that "
            "set ``LANCE_CTS_ENGINE`` — passing ``--engine=legacy`` (or "
            "the env var equivalent) is now an error since the legacy "
            "``textwrap.dedent`` path was removed."
        ),
    )
    args = parser.parse_args()

    engine = resolve_engine(args.engine)
    renderer = TemplateRenderer()

    mappings_dir = Path(args.mappings_dir)
    if not mappings_dir.exists():
        raise SystemExit(
            f"ERROR: mappings directory not found: {mappings_dir}\n"
            "Run `make gen-cts-wiremock` first to generate WireMock mappings."
        )

    # Repo root = ci/cts/gen_wiremock_tests.py → ../.. = repo root.
    repo_root = Path(__file__).resolve().parent.parent.parent
    discover_api_classification(repo_root)

    ops = load_operations(mappings_dir)
    print(f"Found {len(ops)} operations: {', '.join(ops)}")

    # Cross-check: every operation in mappings must be classified in all
    # three generated clients, otherwise the test files we emit would fail
    # to compile / reference missing API methods.
    missing_per_lang = {
        "Rust": [op for op in ops if op not in RUST_API_MODULE],
        "Python": [op for op in ops if op not in PYTHON_API_MODULE],
        "Java": [op for op in ops if op not in JAVA_API_CLASS],
    }
    unclassified = {lang: ops_ for lang, ops_ in missing_per_lang.items() if ops_}
    if unclassified:
        details = "\n".join(
            f"  {lang}: {', '.join(ops_)}" for lang, ops_ in unclassified.items()
        )
        raise SystemExit(
            "ERROR: the following operations from WireMock mappings could not "
            "be located in the generated client API classes:\n"
            f"{details}\n"
            "Either the clients are stale (run `make gen`) or the spec / "
            "mappings are out of sync with the generated code."
        )

    # All four clients are produced via Mustache templates under
    # ``ci/cts/templates/``.  The legacy ``textwrap.dedent`` path was
    # removed once every language reached byte-for-byte parity (see
    # ``ci/cts/REFACTORING_PROGRESS.md``).
    rust_body = generate_rust_mustache(ops, renderer)
    python_body = generate_python_mustache(ops, renderer)
    java_apache_body = generate_java_apache_mustache(ops, renderer)
    java_async_body = generate_java_async_mustache(ops, renderer)

    outputs = {
        Path(args.out_rust): rust_body,
        Path(args.out_python): python_body,
        Path(args.out_java_apache): java_apache_body,
        Path(args.out_java_async): java_async_body,
    }

    print(f"CTS engine: {engine}")

    for out_path, content in outputs.items():
        out_path.parent.mkdir(parents=True, exist_ok=True)
        # Normalize trailing whitespace: strict tools like `cargo fmt --check`
        # reject files that end with multiple blank lines, while a missing
        # trailing newline upsets POSIX-style toolchains.  Force exactly one
        # final '\n' regardless of how individual generators built their
        # buffer.
        normalized = content.rstrip("\n") + "\n"
        out_path.write_text(normalized, encoding="utf-8")
        print(f"Written: {out_path}  ({len(normalized.splitlines())} lines)")

    # Post-process the generated Rust file with rustfmt so long single-line API
    # calls get wrapped to satisfy `cargo fmt --check`.  Silently skip if rustfmt
    # is not on PATH (CI image without Rust toolchain) — the file is still valid
    # Rust syntax, only style differs.
    rust_out = Path(args.out_rust)
    if rust_out.exists() and shutil.which("rustfmt"):
        try:
            subprocess.run(
                ["rustfmt", "--edition", "2021", str(rust_out)],
                check=True,
                capture_output=True,
            )
            print(f"Formatted: {rust_out} (rustfmt)")
        except subprocess.CalledProcessError as exc:
            print(
                f"WARN: rustfmt failed on {rust_out}: "
                f"{exc.stderr.decode(errors='replace').strip()}"
            )


if __name__ == "__main__":
    main()
